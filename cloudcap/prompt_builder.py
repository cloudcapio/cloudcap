import inspect
import json
import cloudcap.aws as aws_module
from cloudcap.cfn_schema import fetch, summarize
from cloudcap.few_shot import get_examples
from cloudcap.metrics import (
    NREQUESTS, DYNAMODB_READ, DYNAMODB_WRITE, S3_GET, S3_PUT, HTTP_METHODS
)
from cloudcap.plugins import Plugin


PLUGIN_INTERFACE = inspect.getsource(Plugin)

METRICS_CONSTANTS = f"""\
NREQUESTS = {NREQUESTS!r}
DYNAMODB_READ = {DYNAMODB_READ!r}
DYNAMODB_WRITE = {DYNAMODB_WRITE!r}
S3_GET = {S3_GET!r}
S3_PUT = {S3_PUT!r}
HTTP_METHODS = {HTTP_METHODS!r}
"""


def _get_resource_class_source(resource_type: str) -> str | None:
    for name, obj in inspect.getmembers(aws_module, inspect.isclass):
        if getattr(obj, "cfn_type", None) == resource_type:
            return inspect.getsource(obj)
    return None


def build(resource_type: str) -> str:
    examples = get_examples()
    schema = summarize(fetch(resource_type))
    resource_class_source = _get_resource_class_source(resource_type)

    parts = []

    parts.append("You are generating a Python Plugin subclass for the cloudcap static analysis tool.")
    parts.append("cloudcap models AWS infrastructure as a constraint graph. Each resource is a node. "
                 "Edges represent message flow between resources. The z3 SMT solver checks that "
                 "user-supplied usage estimates are consistent with the architecture constraints.")

    parts.append("## Plugin base class\n```python\n" + PLUGIN_INTERFACE + "\n```")
    parts.append("## Metric constants\n```python\n" + METRICS_CONSTANTS + "\n```")

    parts.append("## Constraint types\n"
                 "- **Intrinsic**: relationships within a single resource (e.g. api.NREQUESTS = api.GET + api.POST)\n"
                 "- **Outgoing**: edge variable equals source node variable (e.g. queue→lambda.NREQUESTS = queue.NREQUESTS)\n"
                 "- **Incoming**: auto-generated by Analyzer — node variable = sum of all incoming edges. Do NOT add these manually.\n"
                 "- Use `self[resource, metric]` for a node variable.\n"
                 "- Use `self[resource1, resource2, metric]` for an edge variable.\n"
                 "- Use `self.add(constraint)` to register a z3 constraint.\n"
                 "- Use `self.aws.arns` to iterate all resources. Use `self.aws[arn]` to look up by ARN.")

    parts.append("## Examples\n")
    for ex in examples:
        parts.append(f"### {ex['resource_type']}\n"
                     f"CFN schema:\n```json\n{json.dumps(ex['schema'], indent=2)}\n```\n"
                     f"Plugin:\n```python\n{ex['plugin_code']}\n```")

    task = (f"## Your task\n"
            f"Generate a Plugin subclass for `{resource_type}`.\n"
            f"CFN schema:\n```json\n{json.dumps(schema, indent=2)}\n```\n")

    if resource_class_source:
        task += (f"The Python class for this resource is defined as follows — "
                 f"only use attributes that exist on this class:\n"
                 f"```python\n{resource_class_source}\n```\n")

    task += ("Return only the Plugin class in a single fenced ```python code block. "
             "Import nothing beyond what is already available in the plugin's scope "
             "(Plugin base class, aws resource classes, and metric constants are all in scope). "
             "Only access attributes that are explicitly defined on the resource class above.")

    parts.append(task)

    return "\n\n".join(parts)
